def _folder_profile(relative: PurePosixPath) -> dict[str, Any]:
    if not relative.parts:
        return {
            "title": "Node data",
            "abstract": "Published data products provided by this OSWM node.",
            "process": "Generated or collected by the OSWM node pipeline.",
            "sources": ["OSWM node pipeline"],
        }

    key = relative.parts[0] if relative.parts else "data"
    default_title = _humanize(key)
    return FOLDER_PROFILES.get(
        key,
        {
            "title": default_title,
            "abstract": f"Published data products stored below data/{key}.",
            "process": "Generated or collected by the OSWM node pipeline.",
            "sources": ["OSWM node pipeline"],
        },
    )


def _humanize(value: str) -> str:
    value = re.sub(r"\.(metadata\.)?json$", "", value, flags=re.IGNORECASE)
    value = re.sub(r"\.(geojson|parquet|pmtiles|vrt|png|html|csv|txt)$", "", value, flags=re.IGNORECASE)
    return value.replace("_", " ").replace("-", " ").strip().title()


def _media_type(path: Path) -> tuple[str, str]:
    known = MEDIA_TYPES.get(path.suffix.lower())
    if known:
        return known
    guessed, _ = mimetypes.guess_type(path.name)
    return guessed or "application/octet-stream", path.suffix.lstrip(".").upper() or "Binary"


def _resource_type(path: Path) -> str:
    suffix = path.suffix.lower()
    name = path.name.lower()
    if suffix in {".geojson", ".parquet"}:
        return "dataset"
    if suffix == ".pmtiles":
        return "tileset"
    if suffix == ".vrt":
        return "dataset-description"
    if suffix == ".png":
        return "image"
    if suffix == ".html":
        return "document"
    if "report" in name or name in {"metadata.json", "terrain.json"}:
        return "report"
    if "profiles" in name or "rules" in name:
        return "model-configuration"
    if "cache" in name:
        return "cache"
    return "dataset"


def _resource_domain(path: Path, data_root: Path) -> tuple[str, bool]:
    """Return the standards domain and feature-catalogue applicability."""

    relative = path.relative_to(data_root)
    suffix = path.suffix.lower()
    geographic = suffix in GEOGRAPHIC_SUFFIXES
    if relative.parts and relative.parts[0] == "boundaries":
        geographic = True
    if relative.parts[:2] == ("updates", "versioning"):
        geographic = True
    if suffix == ".png" and path.stem.startswith("terrain_"):
        geographic = True
    return ("geographic" if geographic else "non-geographic", suffix in FEATURE_SUFFIXES)


def _collection_domain(directory: Path, data_root: Path) -> tuple[str, bool]:
    domains: set[str] = set()
    include_feature_catalogue = False
    for path in _iter_data_files(directory):
        domain, is_feature_resource = _resource_domain(path, data_root)
        domains.add(domain)
        include_feature_catalogue = include_feature_catalogue or is_feature_resource

    if len(domains) > 1:
        return "mixed", include_feature_catalogue
    if domains:
        return next(iter(domains)), include_feature_catalogue
    return "non-geographic", False


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


