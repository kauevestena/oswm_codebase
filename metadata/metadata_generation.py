def _base_record(
    *,
    context: dict[str, Any],
    identifier: str,
    resource_type: str,
    title: str,
    abstract: str,
    spatial: dict[str, Any] | None,
    updated: str | None,
    registry: dict[str, Any],
    lineage: dict[str, Any],
    revision: dict[str, Any],
    profile_domain: str,
    include_feature_catalogue: bool,
) -> dict[str, Any]:
    return {
        "$schema": SCHEMA_URL,
        "metadata_profile": _profile(profile_domain, include_feature_catalogue),
        "identifier": identifier,
        "resource_type": resource_type,
        "title": title,
        "abstract": abstract,
        "language": context["language"],
        "responsible_parties": _responsible_parties(context),
        "spatial": spatial,
        "temporal": {
            "updated": updated,
            "node_registry": registry,
        },
        "lineage": lineage,
        "quality": _quality(context["base_url"], profile_domain),
        "rights": {
            "statement": (
                "Licensing and attribution follow the upstream sources and the "
                "specific distribution being described."
            )
        },
        "metadata_generation": _generation_info(updated, revision),
    }


def _iter_data_directories(data_root: Path) -> Iterable[Path]:
    yield data_root
    for path in sorted(data_root.rglob("*"), key=lambda item: item.as_posix()):
        if path.is_dir() and not any(part.startswith(".") for part in path.relative_to(data_root).parts):
            yield path


def _iter_data_files(data_root: Path) -> Iterable[Path]:
    for path in sorted(data_root.rglob("*"), key=lambda item: item.as_posix()):
        if not path.is_file():
            continue
        relative = path.relative_to(data_root)
        if any(part.startswith(".") for part in relative.parts):
            continue
        if path.name == "index.json" or path.name.endswith(".tmp"):
            continue
        yield path


def _metadata_path_for_file(path: Path, data_root: Path, metadata_root: Path) -> Path:
    relative = path.relative_to(data_root)
    return metadata_root / relative.parent / f"{relative.name}.metadata.json"


def _collection_metadata_path(directory: Path, data_root: Path, metadata_root: Path) -> Path:
    relative = directory.relative_to(data_root)
    return metadata_root / relative / "index.json"


def _file_record(
    path: Path,
    *,
    data_root: Path,
    metadata_root: Path,
    context: dict[str, Any],
    spatial: dict[str, Any] | None,
    updated: str | None,
    registry: dict[str, Any],
    revision: dict[str, Any],
    calculate_checksums: bool,
) -> tuple[Path, dict[str, Any]]:
    relative = path.relative_to(data_root)
    relative_posix = PurePosixPath(relative.as_posix())
    data_rel = PurePosixPath("data") / relative_posix
    metadata_path = _metadata_path_for_file(path, data_root, metadata_root)
    metadata_rel = metadata_path.relative_to(metadata_root.parent).as_posix()
    profile = _folder_profile(relative_posix)
    media_type, format_name = _media_type(path)
    checksum = _sha256(path) if calculate_checksums else None
    profile_domain, include_feature_catalogue = _resource_domain(path, data_root)

    title = f"{context['city']} — {_humanize(path.name)}"
    abstract = (
        f"{profile['abstract']} This record describes the {format_name} "
        f"distribution at {data_rel.as_posix()}."
    )
    record = _base_record(
        context=context,
        identifier=f"{context['base_url']}{metadata_rel}",
        resource_type=_resource_type(path),
        title=title,
        abstract=abstract,
        spatial=spatial if profile_domain == "geographic" else None,
        updated=updated,
        registry=registry,
        lineage={
            "process_description": profile["process"],
            "sources": profile["sources"],
        },
        revision=revision,
        profile_domain=profile_domain,
        include_feature_catalogue=include_feature_catalogue,
    )
    distribution: dict[str, Any] = {
        "resource_path": data_rel.as_posix(),
        "access_url": f"{context['base_url']}{data_rel.as_posix()}",
        "download_url": f"{context['base_url']}{data_rel.as_posix()}",
        "media_type": media_type,
        "format": format_name,
        "byte_size": path.stat().st_size,
    }
    if checksum is not None:
        distribution["checksum"] = {
            "algorithm": "SHA-256",
            "value": checksum,
        }
    record["distribution"] = distribution
    record["links"] = [
        {"rel": "self", "href": f"{context['base_url']}{metadata_rel}", "type": "application/json"},
        {"rel": "describes", "href": distribution["access_url"], "type": media_type},
        {
            "rel": "collection",
            "href": (
                f"{context['base_url']}"
                f"{metadata_path.parent.relative_to(metadata_root.parent).as_posix()}"
                "/index.json"
            ),
            "type": "application/json",
        },
    ]
    return metadata_path, record


def _collection_record(
    directory: Path,
    *,
    data_root: Path,
    metadata_root: Path,
    context: dict[str, Any],
    spatial: dict[str, Any] | None,
    updated: str | None,
    registry: dict[str, Any],
    revision: dict[str, Any],
    calculate_checksums: bool,
) -> tuple[Path, dict[str, Any]]:
    relative = directory.relative_to(data_root)
    relative_posix = PurePosixPath(relative.as_posix()) if relative.parts else PurePosixPath()
    metadata_path = _collection_metadata_path(directory, data_root, metadata_root)
    metadata_rel = metadata_path.relative_to(metadata_root.parent).as_posix()
    data_rel = PurePosixPath("data") / relative_posix
    profile = _folder_profile(relative_posix)
    collection_title = profile["title"]
    profile_domain, include_feature_catalogue = _collection_domain(directory, data_root)
    if relative.parts[1:]:
        collection_title = f"{collection_title} — {_humanize(relative.name)}"

    record = _base_record(
        context=context,
        identifier=f"{context['base_url']}{metadata_rel}",
        resource_type="catalog" if not relative.parts else "collection",
        title=f"{context['city']} — {collection_title}",
        abstract=(
            f"{profile['abstract']} This collection mirrors {data_rel.as_posix()} "
            "without changing the source data directory."
        ),
        spatial=spatial if profile_domain in {"geographic", "mixed"} else None,
        updated=updated,
        registry=registry,
        lineage={
            "process_description": profile["process"],
            "sources": profile["sources"],
        },
        revision=revision,
        profile_domain=profile_domain,
        include_feature_catalogue=include_feature_catalogue,
    )

    assets: list[dict[str, Any]] = []
    for child in sorted(directory.iterdir(), key=lambda item: item.name):
        if (
            not child.is_file()
            or child.name.startswith(".")
            or child.name == "index.json"
            or child.name.endswith(".tmp")
        ):
            continue
        media_type, format_name = _media_type(child)
        data_child_rel = PurePosixPath("data") / PurePosixPath(child.relative_to(data_root).as_posix())
        child_metadata = _metadata_path_for_file(child, data_root, metadata_root)
        asset: dict[str, Any] = {
            "title": _humanize(child.name),
            "resource": f"{context['base_url']}{data_child_rel.as_posix()}",
            "metadata": f"{context['base_url']}{child_metadata.relative_to(metadata_root.parent).as_posix()}",
            "media_type": media_type,
            "format": format_name,
            "byte_size": child.stat().st_size,
        }
        if calculate_checksums:
            asset["checksum"] = {"algorithm": "SHA-256", "value": _sha256(child)}
        assets.append(asset)

    subcollections = []
    for child in sorted(directory.iterdir(), key=lambda item: item.name):
        if not child.is_dir() or child.name.startswith("."):
            continue
        child_metadata = _collection_metadata_path(child, data_root, metadata_root)
        subcollections.append(
            {
                "title": _humanize(child.name),
                "path": child_metadata.relative_to(metadata_root.parent).as_posix(),
                "href": f"{context['base_url']}{child_metadata.relative_to(metadata_root.parent).as_posix()}",
            }
        )

    record["assets"] = assets
    record["collections"] = subcollections
    record["links"] = [
        {"rel": "self", "href": f"{context['base_url']}{metadata_rel}", "type": "application/json"},
        {"rel": "describes", "href": f"{context['base_url']}{data_rel.as_posix()}/", "type": "text/html"},
    ]
    if relative.parts:
        parent_metadata = _collection_metadata_path(directory.parent, data_root, metadata_root)
        record["links"].append(
            {
                "rel": "collection",
                "href": f"{context['base_url']}{parent_metadata.relative_to(metadata_root.parent).as_posix()}",
                "type": "application/json",
            }
        )
    return metadata_path, record


def _is_generated_record(path: Path) -> bool:
    payload = _load_json(path, {})
    return (
        isinstance(payload, dict)
        and isinstance(payload.get("metadata_generation"), dict)
        and payload["metadata_generation"].get("generator") == GENERATOR_ID
    )


def _prune_stale_generated_records(metadata_root: Path, expected: set[Path]) -> list[str]:
    removed: list[str] = []
    if not metadata_root.exists():
        return removed
    for path in sorted(metadata_root.rglob("*.json"), reverse=True):
        if path in expected or not _is_generated_record(path):
            continue
        path.unlink()
        removed.append(path.relative_to(metadata_root.parent).as_posix())
    for directory in sorted(
        (path for path in metadata_root.rglob("*") if path.is_dir()),
        key=lambda item: len(item.parts),
        reverse=True,
    ):
        try:
            directory.rmdir()
        except OSError:
            pass
    return removed


def generate_metadata(
    node_root: str | Path = ".",
    *,
    calculate_checksums: bool = True,
    clean_stale: bool = True,
) -> dict[str, Any]:
    """Generate and validate the sibling metadata tree for one OSWM node."""

    root = Path(node_root).resolve()
    data_root = root / "data"
    metadata_root = root / "metadata"
    if not data_root.is_dir():
        raise FileNotFoundError(f"OSWM data directory not found: {data_root}")

    context = _node_context(root)
    revision = _codebase_revision()
    updated, registry = _parse_registry_timestamp(root, context["timezone"])
    spatial = _boundary_spatial(root, context["base_url"])
    expected: set[Path] = set()
    records_written = 0

    for data_file in _iter_data_files(data_root):
        target, record = _file_record(
            data_file,
            data_root=data_root,
            metadata_root=metadata_root,
            context=context,
            spatial=spatial,
            updated=updated,
            registry=registry,
            revision=revision,
            calculate_checksums=calculate_checksums,
        )
        _atomic_json_dump(record, target)
        expected.add(target)
        records_written += 1

    directories = list(_iter_data_directories(data_root))
    for directory in reversed(directories):
        target, record = _collection_record(
            directory,
            data_root=data_root,
            metadata_root=metadata_root,
            context=context,
            spatial=spatial,
            updated=updated,
            registry=registry,
            revision=revision,
            calculate_checksums=calculate_checksums,
        )
        if directory == data_root:
            record["integrity"] = {
                "data_files": sum(1 for _ in _iter_data_files(data_root)),
                "collections": len(directories) - 1,
                "generated_records": records_written + 1,
            }
        _atomic_json_dump(record, target)
        expected.add(target)
        records_written += 1

    removed = _prune_stale_generated_records(metadata_root, expected) if clean_stale else []
    errors = validate_metadata_tree(root, verify_checksums=False)
    if errors:
        raise RuntimeError("Metadata validation failed:\n- " + "\n- ".join(errors))

    return {
        "node_root": str(root),
        "metadata_root": str(metadata_root),
        "records_written": records_written,
        "stale_records_removed": removed,
        "checksums": calculate_checksums,
    }


def validate_metadata_tree(
    node_root: str | Path = ".",
    *,
    verify_checksums: bool = False,
) -> list[str]:
    """Return integrity errors for the generated node metadata tree."""

    root = Path(node_root).resolve()
    data_root = root / "data"
    metadata_root = root / "metadata"
    errors: list[str] = []
    if not data_root.is_dir():
        return [f"Missing data directory: {data_root}"]
    if not metadata_root.is_dir():
        return [f"Missing metadata directory: {metadata_root}"]

    expected: set[Path] = {
        _collection_metadata_path(directory, data_root, metadata_root)
        for directory in _iter_data_directories(data_root)
    }
    expected.update(
        _metadata_path_for_file(path, data_root, metadata_root)
        for path in _iter_data_files(data_root)
    )

    required = {
        "$schema",
        "metadata_profile",
        "identifier",
        "resource_type",
        "title",
        "abstract",
        "language",
        "responsible_parties",
        "spatial",
        "temporal",
        "lineage",
        "quality",
        "rights",
        "links",
        "metadata_generation",
    }
    for path in sorted(expected):
        if not path.exists():
            errors.append(f"Missing metadata record: {path.relative_to(root)}")
            continue
        payload = _load_json(path, None)
        if not isinstance(payload, dict):
            errors.append(f"Invalid JSON object: {path.relative_to(root)}")
            continue
        missing = sorted(required - payload.keys())
        if missing:
            errors.append(f"{path.relative_to(root)} lacks: {', '.join(missing)}")
        distribution = payload.get("distribution")
        if not isinstance(distribution, dict):
            continue
        resource_path = distribution.get("resource_path")
        if not isinstance(resource_path, str) or not resource_path.startswith("data/"):
            errors.append(f"Invalid resource_path in {path.relative_to(root)}")
            continue
        resource = root / resource_path
        if not resource.is_file():
            errors.append(f"Metadata points to missing resource: {resource_path}")
            continue
        checksum = distribution.get("checksum")
        if verify_checksums and isinstance(checksum, dict) and checksum.get("algorithm") == "SHA-256":
            if checksum.get("value") != _sha256(resource):
                errors.append(f"Checksum mismatch: {resource_path}")

    for path in metadata_root.rglob("*.json"):
        if _is_generated_record(path) and path not in expected:
            errors.append(f"Orphan generated metadata record: {path.relative_to(root)}")
    return errors


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--node-root",
        default=".",
        help="OSWM node root containing config.py and data/ (default: current directory)",
    )
    parser.add_argument(
        "--no-checksums",
        action="store_true",
        help="Skip SHA-256 generation for a faster local preview",
    )
    parser.add_argument(
        "--validate-only",
        action="store_true",
        help="Validate the existing metadata tree without regenerating it",
    )
    parser.add_argument(
        "--verify-checksums",
        action="store_true",
        help="Recalculate and verify all recorded SHA-256 checksums",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    if args.validate_only:
        errors = validate_metadata_tree(args.node_root, verify_checksums=args.verify_checksums)
        if errors:
            print("Metadata validation failed:")
            for error in errors:
                print(f"- {error}")
            return 1
        print("Metadata validation succeeded.")
        return 0

    summary = generate_metadata(
        args.node_root,
        calculate_checksums=not args.no_checksums,
        clean_stale=True,
    )
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
