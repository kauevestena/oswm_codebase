def metadata_relative_path_for_data(data_path: str | Path) -> str:
    """Return the deterministic metadata path for a path below ``data/``.

    Directory manifests named ``index.json`` map directly to the mirrored
    collection record.  Other files retain their complete filename and gain a
    ``.metadata.json`` suffix, preventing collisions between equal stems with
    different formats.
    """

    normalized = str(data_path).replace("\\", "/").lstrip("./")
    pure = PurePosixPath(normalized)
    if not pure.parts or pure.parts[0] != "data":
        raise ValueError(f"Expected a path below data/: {data_path}")

    relative = PurePosixPath(*pure.parts[1:])
    if relative.name == "index.json":
        return str(PurePosixPath("metadata") / relative)
    return str(
        PurePosixPath("metadata")
        / relative.parent
        / f"{relative.name}.metadata.json"
    )


def _load_json(path: Path, default: Any) -> Any:
    try:
        with path.open("r", encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError, TypeError):
        return default


def _atomic_json_dump(payload: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    with temporary.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, ensure_ascii=False)
        handle.write("\n")
    os.replace(temporary, path)


def _load_node_config(node_root: Path) -> Any:
    config_path = node_root / "config.py"
    if not config_path.exists():
        raise FileNotFoundError(f"OSWM node config not found: {config_path}")

    module_name = f"oswm_node_config_{hash(config_path.resolve())}"
    spec = importlib.util.spec_from_file_location(module_name, config_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Could not load OSWM node config: {config_path}")
    module = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(node_root))
    try:
        spec.loader.exec_module(module)
    finally:
        try:
            sys.path.remove(str(node_root))
        except ValueError:
            pass
    return module


def _node_context(node_root: Path) -> dict[str, Any]:
    config = _load_node_config(node_root)
    city = str(getattr(config, "CITY_NAME", node_root.name))
    username = str(getattr(config, "USERNAME", "unknown"))
    repository = str(getattr(config, "REPO_NAME", node_root.name))
    language = str(getattr(config, "METADATA_LANGUAGE", "en"))
    base_url = str(
        getattr(
            config,
            "NODE_BASE_URL",
            f"https://{username}.github.io/{repository}/",
        )
    ).rstrip("/") + "/"
    timezone_name = str(getattr(config, "METADATA_TIMEZONE", "UTC"))

    return {
        "city": city,
        "username": username,
        "repository": repository,
        "language": language,
        "base_url": base_url,
        "timezone": timezone_name,
        "repository_url": f"https://github.com/{username}/{repository}",
    }


def _profile(domain: str, include_feature_catalogue: bool) -> dict[str, Any]:
    aligned_with = [ALIGNED_STANDARDS[0]]
    if domain in {"geographic", "mixed"}:
        aligned_with.extend(ALIGNED_STANDARDS[1:4])
        if include_feature_catalogue:
            aligned_with.append(ALIGNED_STANDARDS[4])

    return {
        "name": "OSWM Metadata Profile",
        "version": PROFILE_VERSION,
        "encoding": "application/json",
        "alignment": "conceptual",
        "domain": domain,
        "aligned_with": aligned_with,
        "conformance_note": (
            "This is an OSWM JSON application profile. Geographic ISO concepts "
            "are applied only to geographic or mixed resources; the profile does "
            "not claim conformance to the ISO 19115-3 XML encoding."
        ),
    }


def _codebase_revision() -> dict[str, str | None]:
    codebase_root = Path(__file__).resolve().parents[1]

    def git_value(*args: str) -> str | None:
        try:
            result = subprocess.run(
                ["git", *args],
                cwd=codebase_root,
                check=True,
                capture_output=True,
                text=True,
                timeout=10,
            )
        except (OSError, subprocess.SubprocessError):
            return None
        value = result.stdout.strip()
        return value or None

    return {
        "repository": "https://github.com/kauevestena/oswm_codebase",
        "commit": git_value("rev-parse", "HEAD"),
        "commit_date": git_value("show", "-s", "--format=%cI", "HEAD"),
    }


def _parse_registry_timestamp(node_root: Path, timezone_name: str) -> tuple[str | None, dict[str, Any]]:
    registry = _load_json(node_root / "data" / "updates" / "registry.json", {})
    if not isinstance(registry, dict):
        return None, {}

    tz = timezone.utc
    if ZoneInfo is not None:
        try:
            tz = ZoneInfo(timezone_name)
        except (KeyError, ValueError):
            tz = timezone.utc

    parsed: list[datetime] = []
    for value in registry.values():
        if not isinstance(value, str):
            continue
        for pattern in ("%d/%m/%Y %H:%M:%S", "%Y-%m-%dT%H:%M:%S%z"):
            try:
                candidate = datetime.strptime(value, pattern)
                if candidate.tzinfo is None:
                    candidate = candidate.replace(tzinfo=tz)
                parsed.append(candidate)
                break
            except ValueError:
                continue

    updated = max(parsed).isoformat() if parsed else None
    return updated, registry


def _boundary_spatial(node_root: Path, base_url: str) -> dict[str, Any] | None:
    info = _load_json(node_root / "data" / "boundaries" / "infos.json", {})
    bbox = info.get("bbox") if isinstance(info, dict) else None
    if not (
        isinstance(bbox, list)
        and len(bbox) == 4
        and all(isinstance(value, (int, float)) for value in bbox)
    ):
        return None
    spatial = {
        "scope": "node_coverage",
        "bbox": bbox,
        "bbox_order": ["west", "south", "east", "north"],
        "reference_system": "http://www.opengis.net/def/crs/OGC/1.3/CRS84",
    }
    if (node_root / "data" / "boundaries" / "polygon.geojson").is_file():
        spatial["geometry"] = f"{base_url}data/boundaries/polygon.geojson"
    return spatial


