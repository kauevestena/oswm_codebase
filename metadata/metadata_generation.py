"""Generate a deterministic, ISO-aligned metadata tree for an OSWM node.

The generator deliberately leaves ``data/`` untouched.  It mirrors every data
directory below the sibling ``metadata/`` directory, writes one collection
record as ``index.json`` in each mirrored directory, and writes a JSON sidecar
for every non-index data file.

This is an OSWM JSON application profile.  It aligns its concepts with the ISO
standards listed in :data:`ALIGNED_STANDARDS`; it is not the XML encoding
defined by ISO 19115-3.
"""

